"""Write EXPERIMENTS.md from reports/experiments/results.json (no number is typed by hand).

    python -m src.report_experiments
"""
import json

from src.config import REPORTS_DIR, ROOT

R = json.loads((REPORTS_DIR / "experiments" / "results.json").read_text())
V2 = json.loads((REPORTS_DIR / "v2" / "metrics.json").read_text())
LAT = json.loads((REPORTS_DIR / "v2" / "latency.json").read_text()) if (REPORTS_DIR / "v2" / "latency.json").exists() else None
f3 = lambda v: "–" if v is None else f"{v:.3f}"
pc = lambda v, d=1: "–" if v is None else f"{v * 100:.{d}f}%"
lk = lambda v: f"₹{v / 1e5:,.2f}L"


def table(head, rows):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(map(str, r)) + " |" for r in rows])


def compare_table(block):
    res = block["results"]
    rows = [[k, f3(v["pr_auc"]), f3(v["roc_auc"]), f3(v["recall_at_1pct_fpr"]), f3(v["precision_at_80pct_recall"]),
             f3(v["precision"]), f3(v["recall"]), f3(v["f1"]), pc(v["fpr"], 2), lk(v["loss_inr"])] for k, v in res.items()]
    return table(["Model", "PR-AUC", "ROC-AUC", "Recall @1% FPR", "Precision @80% recall", "Precision", "Recall", "F1",
                  "FPR", "Loss"], rows) + f"\n\nNo-model loss on the same test period: {lk(block['no_model_loss_inr'])}."


def lopo_table(lp):
    rows = []
    for p, v in lp.items():
        a = v["adaptation"]
        rows.append([p, v["n_test"], pc(v["supervised_only"], 0), pc(v["fused_score"], 0),
                     " / ".join(pc(v.get(f"{k}_tripwire", 0), 0) for k in ("payee", "device", "flow", "ae")),
                     pc(v["hybrid_system"], 0), pc(a["champion_eval_recall"], 0),
                     " → ".join(pc(a[f"after_{k}d_feedback"]["eval_recall"], 0) for k in (1, 3, 5)),
                     a["after_5d_feedback"]["labels_used"]])
    m = lambda key: sum(v[key] for v in lp.values()) / len(lp)
    rows.append(["**mean**", "", pc(m("supervised_only"), 0), pc(m("fused_score"), 0), "", f"**{pc(m('hybrid_system'), 0)}**",
                 "", "", ""])
    return table(["Held-out pattern", "Test cases", "Supervised", "Fused score", "Tripwires payee/device/flow/AE",
                  "Hybrid system", "Eval period (no feedback)", "After 1 / 3 / 5 days of labels", "Labels used (5 d)"], rows) + \
        f"\n\nHybrid system cost across these runs: mean precision {pc(m('hybrid_overall_precision'))}, mean false-positive rate {pc(m('hybrid_overall_fpr'), 2)}."


def main():
    c, t = R["compare"], V2["test"]
    out = [f"""# payTrace 2.0 — Experimental evaluation

Generated by `python -m src.report_experiments` from `reports/experiments/results.json` ({R.get('generated_at', '')}).
Reproduce everything with `python -m src.experiments` (about 25 minutes on a laptop).

> **Real and public data:** see [REAL_DATA.md](REAL_DATA.md); the app now runs on a model trained on Kaggle Sparkov data.
>
> **All results below are on synthetic data.** They show that the methods work and how they compare under controlled
> conditions. They are not estimates of real-world fraud-detection performance.

## 1. Protocol

* **Temporal slices** (fractions of the time span): train 0–50%, early stopping 50–60%, calibration + fusion 60–67%,
  threshold selection 67–75%, **untouched test 75–100%**. For the 60-day data: days 0–30 / 30–36 / 36–40 / 40–45 / 45–60.
* Models never see the test slice. Thresholds are chosen on the threshold slice only. Baselines use the same slices.
* **Datasets:** `v1` = original synthetic data (kept as the baseline dataset); `v2` = harder synthetic data built after
  the audit (fraud in every category, fresh attacker devices, mules with genuine activity, new customers, 7 patterns);
  `v2 seed 11` = the same generator with a different seed, **used once, after the design was frozen**, as confirmation.
* **Costs:** a missed fraud costs its amount; a false alarm costs ₹100.
* **Label delay:** confirmed-fraud graph features only see labels 3 days after the payment.

## 2. Deployed system (v2 data, test period)

{table(["Measure", "Value"], [
        ["PR-AUC (fused risk)", f3(t['ranking']['pr_auc'])], ["ROC-AUC", f3(t['ranking']['roc_auc'])],
        ["Recall @1% FPR", f3(t['ranking']['recall_at_1pct_fpr'])],
        ["REVIEW tier precision / recall / FPR", f"{pc(t['review_tier']['precision'])} / {pc(t['review_tier']['recall'])} / {pc(t['review_tier']['fpr'], 2)}"],
        ["BLOCK tier precision / recall", f"{pc(t['block_tier']['precision'])} / {pc(t['block_tier']['recall'])}"],
        ["Loss vs no model", f"{lk(t['review_tier']['loss_inr'])} vs {lk(t['no_model_loss_inr'])}"],
        ["Alerts per day", f"{t['review_tier'].get('alerts_per_day', 0):,.0f}"]])}

Recall by pattern (all patterns present in training): """ + ", ".join(f"{k} {pc(v, 0)}" for k, v in V2["recall_by_pattern"].items()) + ".",
           "## 3. Model comparison\n\n### v2 data\n" + compare_table(c["v2"]),
           "### v1 data (original dataset)\n" + compare_table(c["v1"]) +
           "\n\nOn v1 data the new features add little (PR-AUC is limited by the QR-swap pattern, which only appears in the "
           "test period of v1, so no supervised model can learn it).",
           ]
    if "confirm" in R:
        out.append("### Confirmation on fresh data (seed 11, never used during design)\n" + compare_table(R["confirm"]["compare"]))
    out.append("## 4. Unseen-fraud test (leave one pattern out)\n\nEach pattern is removed from every training, calibration and "
               "threshold slice, then appears in the test period. Analysts label only transactions the system alerted on in "
               "the first k test days; a challenger retrained with those labels is evaluated on the following days, which no "
               "model saw.\n\n### Final design (v2 data)\n" + lopo_table(R["lopo"]))
    if "lopo_before_merchant_profile" in R:
        b = R["lopo_before_merchant_profile"]
        out.append("### Design iteration (honest record)\nThe first version (one graph detector, no merchant behaviour profile) "
                   f"reached a mean hybrid recall of {pc(sum(v['hybrid_system'] for v in b.values()) / len(b), 0)}. Diagnosis: no "
                   "feature described merchant behaviour, and one combined graph detector diluted device signals; the fusion layer "
                   "(fitted on known fraud) down-weighted anomaly evidence. Changes: merchant behaviour profile, one novelty detector "
                   "per entity type, and REVIEW when fused risk OR the supervised model OR any tripwire fires. Because these changes "
                   "were made after looking at test results, the seed-11 confirmation below is the unbiased check.")
    if "confirm" in R:
        out.append("### Confirmation on fresh data (seed 11)\n" + lopo_table(R["confirm"]["lopo"]))
    ab = R.get("ablation", {})
    if ab:
        out.append("## 5. Ablation (LightGBM, v2 test)\n" + table(["Configuration", "PR-AUC", "Recall @1% FPR"],
                   [[k, f3(v["pr_auc"]), f3(v["recall_at_1pct_fpr"])] for k, v in ab.items()]) +
                   "\n\nSingle runs; differences below about 0.01 PR-AUC should be treated as noise.")
    an = R.get("anomaly", {})
    if an:
        out.append("## 6. Unsupervised detectors alone\n" + table(["Detector", "PR-AUC", "Recall at 0.1% alert budget"],
                   [[k, f3(v["pr_auc"]), pc(v.get("recall_at_0.1pct_alert_budget"))] for k, v in an.items()]) +
                   "\n\nAlone they are weak; their value is catching patterns the supervised model has never seen (section 4).")
    if "hpo" in R:
        h = R["hpo"]
        out.append(f"## 7. Hyperparameter search\n{len(h['trials'])} random LightGBM configurations, selected on the early-stopping "
                   f"slice: test PR-AUC {f3(h['test_pr_auc_default'])} (default) vs {f3(h['test_pr_auc_tuned'])} (best). The gain "
                   f"is too small to justify a different default.")
    cal = R.get("calibration")
    if cal:
        cb = cal["calibration"]
        out.append(f"## 8. Calibration\nBrier score: raw {cb['brier_raw']:.4f}, isotonic {cb['brier_isotonic']:.4f}, fused "
                   f"{cb['brier_fused']:.4f}. Reliability bins are in results.json and on the dashboard.")
        out.append("## 9. Threshold sensitivity (fused risk, test)\n" + table(
            ["Threshold", "Role", "Recall", "Precision", "FPR", "Loss", "Genuine flagged / 10k", "Alerts / day"],
            [[f"{r['threshold']:.4f}", "REVIEW" if r["is_review"] else ("BLOCK" if r["is_block"] else ""), pc(r["recall"]),
              pc(r["precision"]), pc(r["fpr"], 2), lk(r["loss_inr"]), f"{r['genuine_flagged_per_10k']:.0f}",
              f"{r.get('alerts_per_day', 0):.0f}"] for r in cal["thresholds"]]))
        sg = cal["segments"]
        out.append("## 10. Unseen customers and fairness\n" + table(["Customers", "Payments", "Fraud", "PR-AUC", "Recall", "FPR"],
                   [[k, f"{v['n']:,}", v["fraud"], f3(v.get("pr_auc")), pc(v["recall"]), pc(v["fpr"], 2)] for k, v in sg["customers"].items()]))
        for g in ("city", "account_age", "channel"):
            out.append(f"**False-positive rate by {g.replace('_', ' ')}:** " + ", ".join(f"{k} {pc(v['fpr'], 2)}" for k, v in sg[g].items()) + ".")
        out.append("New accounts (< 1 week) have a higher false-positive rate. That is expected (little history) but is a real "
                   "customer-friction cost to monitor; mitigation: step-up verification instead of blocks for new accounts.")
    rb = R.get("robustness")
    if rb:
        out.append("## 11. Robustness\n" + table(["Test-period condition", "PR-AUC", "Recall", "FPR"],
                   [[k, f3(v["pr_auc"]), pc(v["recall"]), pc(v["fpr"], 2)] for k, v in rb.items()]) +
                   "\n\nThis experiment found a critical bug: missing device ids were treated as one shared device, collapsing "
                   "PR-AUC to 0.15 with a 31% false-positive rate. Missing values are now treated as missing (see AUDIT.md).")
    if LAT:
        L = LAT["latency_ms"]
        out.append(f"## 12. Latency\n{LAT['n_transactions']:,} payments scored one at a time ({LAT['machine']}): p50 "
                   f"{L['p50']:.3f} ms, p95 {L['p95']:.3f} ms, p99 {L['p99']:.3f} ms; ~{LAT['throughput_txn_per_sec_single_core']:,.0f} "
                   "payments/s per core. Stage means: " + ", ".join(f"{k} {v * 1000:.0f} µs" for k, v in LAT["stage_mean_ms"].items()) + ".")
    out.append("## 13. Not done, and why\n* **GNNs (GraphSAGE / GAT):** not implemented. The graph signal is already captured online "
               "by payee, device, money-flow and confirmed-fraud graph features (payee graph is the most valuable group in the "
               "ablation), and a GNN would need batch embedding refreshes and a ~700 MB PyTorch dependency without a demonstrated "
               "gain. Next step if real data shows multi-hop structure the features miss.\n"
               "* **Public datasets:** adapters for PaySim and IEEE-CIS are implemented and tested on files in their exact formats, "
               "but Kaggle is not reachable from the build environment, so no public-data results are reported.\n"
               "* **Kafka and PostgreSQL:** code paths exist; no broker or database server was available, so the tested path is the "
               "in-process bus with SQLite.")
    (ROOT / "EXPERIMENTS.md").write_text("\n\n".join(out) + "\n")
    print("wrote", ROOT / "EXPERIMENTS.md")


if __name__ == "__main__":
    main()
