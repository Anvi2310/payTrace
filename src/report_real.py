"""Write REAL_DATA.md from reports/real/results.json and models/ieee_native/meta.json (no hand-typed numbers).

    python -m src.report_real
"""
from __future__ import annotations

import json
import time

from src.config import MODELS_DIR, REPORTS_DIR, ROOT


def pct(v, d=1):
    return "–" if v is None else f"{v * 100:.{d}f}%"


def main():
    r = json.loads((REPORTS_DIR / "real" / "results.json").read_text())
    E, D = r["experiments"], r["datasets"]
    nat_path = MODELS_DIR / "ieee_native" / "meta.json"
    nat = json.loads(nat_path.read_text())["metrics"] if nat_path.exists() else None

    def row(name, x):
        return (f"| {name} | {x['pr_auc']:.3f} | {pct(x['review_recall'])} | {pct(x['review_precision'])} | "
                f"{pct(x['review_fpr'], 2)} | {pct(x['block_recall'])} / {pct(x['block_precision'])} | "
                f"{pct(x['fraud_value_caught_share'])} |")

    head = ("| Model → tested on | PR-AUC | Fraud caught (review+block) | Precision | False alarms | Block recall / precision "
            "| Fraud value caught |\n|---|---|---|---|---|---|---|")
    sp = [("Synthetic-trained (old app model)", E["baseline_synthetic_on_sparkov"]),
          ("**Sparkov-trained (app model)**", E["single_sparkov"]),
          ("Sparkov + IEEE combined", E["pooled_sp_ie"]["sparkov"]),
          ("IEEE-trained (transfer)", E["transfer_ieee_to_sparkov"])]
    ie = [("Synthetic-trained (old app model)", E["baseline_synthetic_on_ieee"]),
          ("IEEE-trained, app fields only", E["single_ieee"]),
          ("Sparkov + IEEE combined", E["pooled_sp_ie"]["ieee"]),
          ("Sparkov-trained (transfer)", E["transfer_sparkov_to_ieee"])]
    native = E.get("ieee_native", {})
    lines = [
        "# payTrace on real and public fraud data",
        "",
        f"Generated by `python -m src.report_real` ({time.strftime('%Y-%m-%d %H:%M')}). Reproduce: download the two Kaggle "
        "datasets into `data/raw/`, then run `python -m src.adapters` (see `src/adapters.py`), "
        "`python -m src.experiments_real`, `python -m src.experiments_real --finish` and `python -m src.train_ieee_native`.",
        "",
        "## Why",
        "",
        "The first payTrace model was trained on synthetic data I generated. Applied to outside data it fails (first row "
        "of each table): it flags almost every payment. Models only learn the fraud that is in their training data.",
        "",
        "## Data",
        "",
        "| Dataset | What it is | Payments | Customers | Fraud rate | Period | Test period (unseen) |",
        "|---|---|---|---|---|---|---|",
        f"| **Sparkov** (Kaggle `kartik2112/fraud-detection`, CC0) | Simulated US card payments (third-party Sparkov generator) "
        f"| {D['sparkov']['rows']:,} | {D['sparkov']['customers']:,} | {pct(D['sparkov']['fraud_rate'], 2)} | "
        f"{D['sparkov']['from'][:10]} → {D['sparkov']['to'][:10]} | {D['sparkov']['test_rows']:,} payments, {D['sparkov']['test_frauds']:,} fraud |",
        f"| **IEEE-CIS** (Kaggle competition, Vesta) | **Real** card-not-present payments, anonymised | {D['ieee']['rows']:,} | "
        f"{D['ieee']['customers']:,} (reconstructed) | {pct(D['ieee']['fraud_rate'], 2)} | 6 months | "
        f"{D['ieee']['test_rows']:,} payments, {D['ieee']['test_frauds']:,} fraud |",
        "",
        "Amounts are converted to rupees at a fixed rate (₹88 per US$) so everything shares the app's currency; the model's "
        "behavioural features are ratios, so the rate barely matters. Personal fields in Sparkov (names, street, job, date of "
        "birth) are dropped. IEEE-CIS has no customer id; the proxy used by top competition solutions (card + address + "
        "account-open day) is used, and it has no merchant id at all.",
        "",
        "## Protocol",
        "",
        "Each dataset keeps its own time split: train 0–50%, early stopping 50–60%, calibration 60–67%, thresholds 67–75%, "
        "**test 75–100% (never used for training or tuning)**. Combined models are tested on each dataset's own test period. "
        "The full payTrace system is used (LightGBM + calibration + Isolation Forests + autoencoder + fusion + review/block "
        "thresholds). PR-AUC: 1.0 is perfect, random guessing scores the fraud rate.",
        "",
        "## Results on Sparkov (test: last 6 months)",
        "",
        head, *[row(n, x) for n, x in sp],
        "",
        "## Results on IEEE-CIS (test: last ~6 weeks, real data)",
        "",
        head, *[row(n, x) for n, x in ie],
    ]
    if native:
        lines += ["",
                  "IEEE-CIS with **all of its own columns** (LightGBM only, same split):",
                  "",
                  "| Features | PR-AUC | ROC-AUC |", "|---|---|---|",
                  *[f"| {k.replace('_', ' ')} ({v['n_features']} columns) | {v['pr_auc']:.3f} | {v['roc_auc']:.3f} |"
                    for k, v in native.items()]]
    if nat:
        lines += ["",
                  f"Saved replay model (`models/ieee_native`, thresholds chosen on the 67–75% slice): PR-AUC {nat['pr_auc']:.3f}, "
                  f"ROC-AUC {nat['roc_auc']:.3f}; review tier catches {pct(nat['review']['recall'])} of fraud at "
                  f"{pct(nat['review']['precision'])} precision and {pct(nat['review']['fpr'], 2)} false alarms; "
                  f"block tier {pct(nat['block']['recall'])} recall at {pct(nat['block']['precision'])} precision."]
    lines += [
        "",
        "## What this shows",
        "",
        f"1. **The synthetic-trained model does not work on outside data** (PR-AUC {E['baseline_synthetic_on_sparkov']['pr_auc']:.2f} "
        f"on Sparkov, {E['baseline_synthetic_on_ieee']['pr_auc']:.3f} on IEEE-CIS; it flags nearly everything).",
        f"2. **Trained on Sparkov, the same system is strong on Sparkov's unseen months**: PR-AUC {E['single_sparkov']['pr_auc']:.3f}, "
        f"{pct(E['single_sparkov']['review_recall'])} of fraud caught with {pct(E['single_sparkov']['review_fpr'], 2)} false alarms. "
        "This is the model the web app now uses. Sparkov is simulated, so this is strong evidence, not proof on real payments.",
        f"3. **On real IEEE-CIS data, the fields a payment form can supply are not enough** (PR-AUC {E['single_ieee']['pr_auc']:.2f}): "
        "most reconstructed customers have one payment and there are no merchant ids. IEEE-CIS's own anonymised columns "
        "carry far more signal; the app replays real IEEE-CIS payments through that model in **Admin → Real data**.",
        "4. **Fraud patterns did not transfer between datasets** (trained on one, tested on the other: near random), and "
        f"**combining them hurt**: Sparkov PR-AUC fell from {E['single_sparkov']['pr_auc']:.2f} to "
        f"{E['pooled_sp_ie']['sparkov']['pr_auc']:.2f} because IEEE-CIS's larger fraud count dominated training.",
        "5. **Adding payTrace's behaviour features to IEEE-CIS's own columns did not help** "
        f"({native.get('raw_plus_behaviour', {}).get('pr_auc', float('nan')):.3f} vs "
        f"{native.get('raw_columns', {}).get('pr_auc', float('nan')):.3f}); training stopped after a few rounds, which "
        "suggests those features drift over the 6 months.",
        "",
        "## Limits",
        "",
        "* No public dataset contains Indian UPI payments with real fraud labels and customer histories. Sparkov is US card "
        "data (simulated); IEEE-CIS is real but anonymised and has no merchants.",
        "* Sparkov has no device data and each customer's city never changes, so the app's model cannot learn device or "
        "location signals from it; the bank policy rules still use them.",
        "* Every model learns the fraud in its own data. The Sparkov model is very good at Sparkov-style fraud (mid-sized "
        "card payments, often at night) and gives only moderate scores to amounts far larger than any fraud it saw, which "
        "is why the policy rules (limits, unverified payees, extreme amounts) stay in front of it.",
        "* The three-way combination (Sparkov + IEEE-CIS + synthetic) ran out of memory in the 8 GB build workspace and was "
        "not retried: combining two datasets already made results worse.",
    ]
    (ROOT / "REAL_DATA.md").write_text("\n".join(lines) + "\n")
    print("wrote REAL_DATA.md")


if __name__ == "__main__":
    main()
