"""Build reports/PAYTRACE_2_FINAL_EVALUATION.md from the JSON outputs in reports/v21/ and reports/real/.
No number in the report is typed by hand.

    python -m src.v21.report
"""
from __future__ import annotations

import json

from src.config import REPORTS_DIR

R = REPORTS_DIR / "v21"


def rd(p):
    f = REPORTS_DIR / p
    return json.loads(f.read_text()) if f.exists() else None


def pct(x, d=1):
    return "–" if x is None else f"{100 * x:.{d}f}%"


def f3(x):
    return "–" if x is None else f"{x:.3f}"


def inr(x):
    return "–" if x is None else f"₹{x:,.0f}"


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    base, real = rd("v21/baseline.json"), rd("real/results.json")
    ieee, unseen, graph = rd("v21/ieee_opt.json"), rd("v21/unseen.json"), rd("v21/graph_eval.json")
    fus = {k: rd(f"v21/fusion_{k}.json") for k in ("v2", "sparkov")}
    bench, lat = rd("v21/bench.json"), rd("v2/latency.json")
    md = ["# payTrace 2.1: final evaluation", "",
          "Generated by `python -m src.v21.report` from `reports/v21/*.json`. Splits are chronological on each dataset's "
          "own timeline: train 0–50%, early stopping 50–60%, calibration 60–67%, thresholds 67–75%, **test 75–100% "
          "(never used for fitting, early stopping, calibration or thresholds)**. Loss = missed fraud value + ₹100 per false "
          "alarm. Three kinds of data are kept apart: **Sparkov** (simulated card payments, the app's model), **IEEE-CIS** "
          "(real Vesta card-not-present payments, anonymised) and **synthetic UPI-style** data (our generator, used where "
          "devices, P2P transfers and labelled fraud patterns are needed). Nothing here was validated on live banking "
          "infrastructure.", ""]

    # 1. baseline
    md += ["## 1. Baseline (payTrace 2.0) reproduced", ""]
    if base:
        sp, ie = base["sparkov_app_model"], base["ieee_native"]
        md += [table(["Model (saved artifact, re-scored)", "Recorded PR-AUC", "Reproduced PR-AUC", "ROC-AUC"],
                     [["Sparkov app model (hybrid, fused risk)", f3(base["recorded"]["single_sparkov"]["pr_auc"]), f3(sp["pr_auc_fused"]), f3(sp["roc_auc_fused"])],
                      ["IEEE-CIS native LightGBM (431 columns)", f3(base["recorded"]["ieee_native"]["pr_auc"]), f3(ie["pr_auc"]), f3(ie["roc_auc"])]]), ""]
    if real:
        e = real["experiments"]
        md += ["Historical 2.0 results kept as baseline (`reports/real/results.json`):", "",
               table(["Model", "Sparkov PR-AUC", "IEEE-CIS PR-AUC"],
                     [["Synthetic-trained model", f3(e["baseline_synthetic_on_sparkov"]["pr_auc"]), f3(e["baseline_synthetic_on_ieee"]["pr_auc"])],
                      ["Trained on that dataset (common features)", f3(e["single_sparkov"]["pr_auc"]), f3(e["single_ieee"]["pr_auc"])],
                      ["Pooled Sparkov + IEEE-CIS", f3(e["pooled_sp_ie"]["sparkov"]["pr_auc"]), f3(e["pooled_sp_ie"]["ieee"]["pr_auc"])],
                      ["Transfer from the other dataset", f3(e["transfer_ieee_to_sparkov"]["pr_auc"]), f3(e["transfer_sparkov_to_ieee"]["pr_auc"])],
                      ["IEEE-CIS native, 431 raw columns", "–", f3(e["ieee_native"]["raw_columns"]["pr_auc"])],
                      ["IEEE-CIS native + behaviour features", "–", f3(e["ieee_native"]["raw_plus_behaviour"]["pr_auc"]) + f" (stopped at iteration {e['ieee_native']['raw_plus_behaviour']['best_iteration']})"]]), ""]

    # 2. IEEE
    if ieee and ieee.get("experiments"):
        ex = ieee["experiments"]
        md += ["## 2. IEEE-CIS (real data) model comparison and ablation", "",
               "`python -m src.v21.ieee_opt run <experiment>`. LightGBM unless stated; early stopping patience 200 rounds.", "",
               table(["Experiment", "Learner", "Features", "Iterations", "PR-AUC", "ROC-AUC", "Recall @1% FPR", "Recall @5% FPR",
                      "Review precision", "Review recall", "Review F1", "Review FPR", "Fraud value caught", "Loss", "Brier (isotonic)", "Predict ms/txn"],
                     [[k, v["learner"], v["n_features"], v["best_iteration"], f3(v["pr_auc"]), f3(v["roc_auc"]), pct(v["recall_at_1pct_fpr"]),
                       pct(v["recall_at_5pct_fpr"]), pct(v["review"]["precision"]), pct(v["review"]["recall"]), f3(v["review"]["f1"]),
                       pct(v["review"]["fpr"], 2), pct(v["review"]["fraud_value_caught_pct"]), inr(v["review"]["loss_inr"]),
                       f"{v['calibration']['brier_isotonic']:.4f}", f"{v['predict_ms_per_txn']:.4f}"] for k, v in ex.items()]), ""]
        if "diagnose" in ieee:
            d = ieee["diagnose"]
            md += ["**Why did '+behaviour' score 0.394 in 2.0?** It stopped at iteration 9 (early-stopping patience 100). "
                   f"With patience 200 the same 470 features train to {ex.get('raw_plus_behaviour', {}).get('best_iteration', '–')} iterations "
                   f"and score {f3(ex.get('raw_plus_behaviour', {}).get('pr_auc'))}, above raw columns alone. "
                   f"Behaviour features whose distribution shifts between the training and early-stopping slices (PSI > 0.25): "
                   f"{', '.join(c[2:] for c in d['unstable_psi_gt_0.25'])}. Constant on IEEE-CIS (no P2P, one channel): "
                   f"{', '.join(c[2:] for c in d['constant'])}. Removing the unstable ones did not help "
                   f"({f3(ex.get('raw_plus_stable_behaviour', {}).get('pr_auc'))}).", ""]
        if "selection" in ieee:
            sel = ieee["selection"]
            md += [f"**Feature selection (train slice only):** {sel['raw_columns']} raw columns; median missing share "
                   f"{pct(sel['missing_share_summary']['median'])}, {pct(sel['missing_share_summary']['share_cols_over_50pct'])} of columns over 50% missing; "
                   f"dropped {len(sel['dropped_mostly_missing'])} >99% missing, {len(sel['dropped_constant'])} constant, "
                   f"{sel['dropped_correlated_V']} V columns >0.98 correlated within the same missing pattern; kept {sel['kept_raw']} raw "
                   f"+ engineered = {sel['selected_total']} features.", ""]
        if "raw_plus_engineered" in ex:
            top = ex["raw_plus_engineered"].get("top_features_gain", {})
            md += ["Top features by gain (raw + engineered): " + ", ".join(list(top)[:12]) + ".", "",
                   "**About the delayed fraud label.** `uid_conf_fraud_past` counts earlier payments of the same card holder "
                   "whose fraud label is at least 7 days old (a chargeback arriving). It is past-only and realistic for a bank "
                   "that learns of chargebacks, but on IEEE-CIS it is strong because the dataset labels every later payment of "
                   "a defrauded account as fraud, while a real bank would usually have blocked the card. The label-free result "
                   "is the conservative improvement; the 30-day variant shows sensitivity to how fast labels arrive.", "",
                   "**Which model runs in the app's Real-data replay.** `raw_plus_engineered` (LightGBM, default settings) was "
                   "fixed in advance as the main experiment; it is NOT the best test score in the table (unweighted and tuned "
                   "LightGBM score a little higher), because picking the winner by its test score would leak the test period "
                   "into model selection. Learner choice matters little (LightGBM, XGBoost and CatBoost are within 0.005 PR-AUC "
                   "on the same features); the engineered features matter a lot. `selected_spw20` stopped at iteration 2 "
                   "(heavy class weighting makes the early-stopping loss rise at once), so its score reflects early stopping, "
                   "not the weighting itself.", ""]

    # 3. unseen
    if unseen:
        ks = ["lightgbm", "isolation_forest", "autoencoder", "hybrid_2_0", "graph_assisted_2_1"]
        names = ["LightGBM", "Isolation Forest", "Autoencoder", "Hybrid 2.0", "Hybrid + rings 2.1"]
        md += ["## 3. Previously unseen fraud (leave one pattern out, synthetic UPI-style data)", "",
               "`python -m src.v21.unseen_fusion unseen`. Each pattern is removed from every fitting slice and appears only in "
               "the test period. Isolation Forest and autoencoder are flagged at the score only 1% of genuine threshold-slice "
               "payments exceed. Delay = hours from the pattern's first test payment to its first alert.", "",
               table(["Held-out pattern", "Test cases"] + [f"{n} recall" for n in names] + ["Delay 2.0 (h)", "Delay 2.1 (h)", "PR-AUC LightGBM", "PR-AUC IF", "PR-AUC AE"],
                     [[p, r["n_test"]] + [pct(r["detectors"][k]["recall"], 0) for k in ks]
                      + [("–" if r["detectors"]["hybrid_2_0"]["detection_delay_hours"] is None else f"{r['detectors']['hybrid_2_0']['detection_delay_hours']:.1f}"),
                         ("–" if r["detectors"]["graph_assisted_2_1"]["detection_delay_hours"] is None else f"{r['detectors']['graph_assisted_2_1']['detection_delay_hours']:.1f}"),
                         f3(r["detectors"]["lightgbm"]["pr_auc_on_pattern"]), f3(r["detectors"]["isolation_forest"]["pr_auc_on_pattern"]),
                         f3(r["detectors"]["autoencoder"]["pr_auc_on_pattern"])] for p, r in unseen["patterns"].items()]
                     + [["**mean**", ""] + [f"**{pct(unseen['mean_recall'][k], 0)}**" for k in ks] + ["", "", "", "", ""],
                        ["mean false-positive rate", ""] + [pct(unseen["mean_fpr"][k], 2) for k in ks] + ["", "", "", "", ""]]), "",
               "Loss on each held-out pattern (missed fraud of that pattern + ₹100 per false alarm in the test period):", "",
               table(["Held-out pattern"] + names, [[p] + [inr(r["detectors"][k]["loss_inr"]) for k in ks] for p, r in unseen["patterns"].items()]), ""]

    # 4. graph
    if graph:
        tl, el = graph["transaction_level"], graph["entity_level"]
        pats = list(tl["rules"]["any"]["recall"])
        md += ["## 4. Fraud-ring detection (synthetic UPI-style data, test period)", "",
               "`python -m src.v21.graph_eval`. Online ring rules (past-only, fixed thresholds) per transaction:", "",
               table(["Ring rule", "False-positive rate", "All fraud"] + pats,
                     [[k, pct(v["fpr"], 3), pct(v["recall_all_fraud"])] + [pct(v["recall"][p], 0) for p in pats] for k, v in tl["rules"].items()]), "",
               f"Ring-monitor cost: {tl['ms_per_txn']:.3f} ms per payment.", "",
               f"Offline ring reports (7-day windows): {el['ring_entities']:,} entities in reported rings; "
               f"**{pct(el['precision'], 0)} of them are touched by fraud**; reported rings cover **{pct(el['fraud_entity_recall'], 0)} "
               f"of the {el['fraud_entities']} fraud entities** (shared ring devices, collector payees, mule accounts).", "",
               table(["Window from", "Payments", "Rings", "Ring entities", "Precision", "Fraud-entity recall", "Cycles", "Chains", "Seconds"],
                     [[w["from"], f"{w['payments']:,}", w["rings"], w["ring_entities"], pct(w["precision"], 0), pct(w["fraud_entity_recall"], 0),
                       w["cycles"], w["chains"], w["analyse_seconds"]] for w in el["windows"]]), "",
               "Caveats: the ring rules were written knowing the generator's pattern descriptions, so these numbers are "
               "optimistic; the ring grouping (suspicious subgraph instead of Louvain on the whole graph, then ≥ 2 customers "
               "per ring) was revised after viewing test-period entity precision. GNNs were not built: no measured gain over "
               "these online graph features.", ""]

    # 5. fusion
    for ds, f in fus.items():
        if not f:
            continue
        md += [f"## 5{'a' if ds == 'v2' else 'b'}. Risk-fusion ablation ({'synthetic UPI-style' if ds == 'v2' else 'Sparkov'}, test period)", "",
               f"`python -m src.v21.unseen_fusion fusion {ds}`. Same saved detectors; only the logistic fusion (fitted on the "
               "calibration slice) and its cost-chosen threshold change.", "",
               table(["Variant", "PR-AUC", "Recall @1% FPR", "Brier", "ECE", "Review precision", "Review recall", "Review FPR", "Loss", "Block precision"],
                     [[k, f3(v["pr_auc"]), pct(v["recall_at_1pct_fpr"]), f"{v['brier']:.4f}", f"{v['ece']:.4f}", pct(v["review"]["precision"]),
                       pct(v["review"]["recall"]), pct(v["review"]["fpr"], 2), inr(v["review"]["loss_inr"]), pct(v["block"]["precision"])]
                      for k, v in f["variants"].items()]), ""]
        dr = f["deployed_rule"]["review_or_block"]
        md += [f"Deployed decision rule (fused risk OR supervised OR any tripwire): precision {pct(dr['precision'])}, recall "
               f"{pct(dr['recall'])}, FPR {pct(dr['fpr'], 2)}, loss {inr(dr['loss_inr'])}; "
               f"{pct(f['deployed_rule']['tripwire_only_alerts_share'])} of alerts come from tripwires alone."]
        if "deployed_rule_plus_rings" in f:
            r2 = f["deployed_rule_plus_rings"]
            md += [f"With 2.1 ring signals: precision {pct(r2['precision'])}, recall {pct(r2['recall'])}, FPR {pct(r2['fpr'], 2)}, "
                   f"loss {inr(r2['loss_inr'])} (on patterns the model already knows, rings add false positives without recall gain; "
                   "their value is on unseen patterns, section 3)."]
        corr = f["detector_correlation_spearman"]
        md += ["", "Detector correlation (Spearman, test payments): " + "; ".join(
            f"{a} vs {b} {corr[a][b]:+.2f}" for a in corr for b in corr if a < b) + ".", "",
               "Threshold sensitivity of the full fusion:", "",
               table(["Threshold", "Precision", "Recall", "FPR", "Loss", "Alerts/day"],
                     [[f"{t['threshold']:.4f}", pct(t["precision"]), pct(t["recall"]), pct(t["fpr"], 2), inr(t["loss_inr"]),
                       f"{t['alerts_per_day']:.0f}"] for t in f["threshold_sensitivity"]]), ""]

    # 6. performance
    md += ["## 6. Latency and throughput", ""]
    if bench:
        md += [table(["Path (Sparkov app model, " + str(bench["payments"]) + " payments)", "p50 ms", "p95 ms", "p99 ms"],
                     [["Full decision (limits, scoring, rings, policy, explanation, SQLite writes)", f"{bench['decision_path_ms']['p50']:.2f}",
                       f"{bench['decision_path_ms']['p95']:.2f}", f"{bench['decision_path_ms']['p99']:.2f}"],
                      ["Scorer (features + 4 detectors + fusion + SHAP)", f"{bench['scorer_ms']['p50']:.2f}", f"{bench['scorer_ms']['p95']:.2f}", f"{bench['scorer_ms']['p99']:.2f}"],
                      ["Fraud-ring monitor", f"{bench['ring_monitor_ms']['p50']:.3f}", f"{bench['ring_monitor_ms']['p95']:.3f}", f"{bench['ring_monitor_ms']['p99']:.3f}"]]),
               "", f"Throughput of the full decision path: {bench['decision_throughput_per_sec']:.0f} payments/s on one thread ({bench['note']})."]
    if lat:
        md += [f"2.0 scorer benchmark (synthetic data): p50 {lat['latency_ms']['p50']:.2f} ms, p99 {lat['latency_ms']['p99']:.2f} ms, "
               f"{lat['throughput_txn_per_sec_single_core']:.0f} payments/s per core."]
    md += ["", "## 7. Limitations", "",
           "* Sparkov and the synthetic UPI-style data are simulated; IEEE-CIS is real but anonymised. Real-bank performance will differ.",
           "* The app's model (Sparkov) has never seen devices or P2P transfers; in the app, device and mule signals come from the ring monitor and policy rules.",
           "* Unseen-fraud and ring results are on our own generator; the ring rules were designed with knowledge of its patterns.",
           "* The IEEE-CIS gain depends mostly on delayed fraud labels of the same card holder; the label-free gain is smaller (section 2).",
           "* No live validation, no production deployment claims."]
    out = REPORTS_DIR / "PAYTRACE_2_FINAL_EVALUATION.md"
    out.write_text("\n".join(md) + "\n")
    print(f"wrote {out} ({len(md)} lines)")


if __name__ == "__main__":
    main()
